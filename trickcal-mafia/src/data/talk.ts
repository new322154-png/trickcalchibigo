/** 이름 뒤 조사 (받침 있으면 앞, 없으면 뒤) */
const JOSA: Record<string, [string, string]> = {
  이다: ['이다', '다'], 이라고: ['이라고', '라고'], 이에요: ['이에요', '예요'], 이야: ['이야', '야'], 이었: ['이었', '였'], 이라는: ['이라는', '라는'],
  가: ['이', '가'], 는: ['은', '는'], 를: ['을', '를'], 와: ['과', '와'], 야: ['아', '야'], 로: ['으로', '로'], 부터: ['부터', '부터'], 한테: ['한테', '한테'],
};

function hasBatchim(word: string) {
  const ch = word[word.length - 1];
  if (/[LMNlmn]/.test(ch)) return true; // 엘·엠·엔
  const code = ch.charCodeAt(0) - 0xac00;
  if (code < 0 || code > 11171) return false;
  return code % 28 !== 0;
}

export function fill(tpl: string, vars: Record<string, string>) {
  return tpl.replace(/\{(\w+)(?::([가-힣]+))?\}/g, (_, k: string, j?: string) => {
    const v = vars[k] ?? '';
    if (!j) return v;
    const pair = JOSA[j];
    if (!pair) return v + j;
    if (j === '로' && /[Ll]$/.test(v)) return v + '로';
    return v + (hasBatchim(v) ? pair[0] : pair[1]);
  });
}

/** 성격에 맞게 말버릇 붙이기 */
export function flavor(p: PersonaId, text: string, rnd: () => number): string {
  let t = text;
  if (rnd() < 0.3) {
    const o = OPENERS[p][Math.floor(rnd() * OPENERS[p].length)];
    t = `${o} ${t}`;
  }
  if (p === 'timid') t = t.replace(/\.$/, '…');
  if (p === 'hot' && rnd() < 0.4) t = t.replace(/\.$/, '!');
  if (p === 'naive' && rnd() < 0.4) t = t.replace(/\.$/, '!');
  return t;
}
